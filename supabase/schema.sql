-- 1. TABELA DE CATEGORIAS
CREATE TABLE IF NOT EXISTS public.categorias (
    id TEXT PRIMARY KEY,
    nome TEXT NOT NULL,
    nome_curto TEXT NOT NULL,
    icone TEXT NOT NULL DEFAULT '📦',
    subtitulo TEXT DEFAULT '',
    ordem INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. TABELA DE PRODUTOS
CREATE TABLE IF NOT EXISTS public.produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    categoria TEXT REFERENCES public.categorias(id) ON DELETE SET NULL,
    categoria_label TEXT DEFAULT '',
    descricao TEXT DEFAULT '',
    preco_antigo NUMERIC(10, 2) DEFAULT 0,
    preco NUMERIC(10, 2) NOT NULL DEFAULT 0,
    emoji TEXT DEFAULT '⭐',
    imagem TEXT DEFAULT '',
    cor_fundo TEXT DEFAULT 'linear-gradient(135deg, #FFF9E6, #FFF0F5)',
    tag_preview TEXT DEFAULT '',
    destaque TEXT DEFAULT '',
    permite_nome BOOLEAN DEFAULT TRUE,
    detalhes_extras TEXT DEFAULT '',
    dimensoes TEXT DEFAULT '',
    quantidade_folhas TEXT DEFAULT '',
    galeria_fotos TEXT[] DEFAULT '{}',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Garante as colunas extras em bancos já criados anteriormente
ALTER TABLE public.produtos ADD COLUMN IF NOT EXISTS detalhes_extras TEXT DEFAULT '';
ALTER TABLE public.produtos ADD COLUMN IF NOT EXISTS dimensoes TEXT DEFAULT '';
ALTER TABLE public.produtos ADD COLUMN IF NOT EXISTS quantidade_folhas TEXT DEFAULT '';
ALTER TABLE public.produtos ADD COLUMN IF NOT EXISTS galeria_fotos TEXT[] DEFAULT '{}';

-- 3. TABELA DE CONFIGURAÇÕES DA LOJA
